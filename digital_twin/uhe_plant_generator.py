    def generate_uhe_autocad_dxf(self, uhe_name: str) -> str:
        """Gerar arquivo DXF da planta da UHE para AutoCAD"""
        
        # Encontrar dados da UHE
        uhe_data = None
        for uhe in self.uhe_database:
            if uhe["name"].lower() == uhe_name.lower():
                uhe_data = uhe
                break
        
        if not uhe_data:
            return f"❌ UHE '{uhe_name}' não encontrada na base de dados"
        
        filename = f"uhe_{uhe_name.lower().replace(' ', '_')}_plant_{datetime.now().strftime('%Y%m%d_%H%M%S')}.dxf"
        
        print(f"🏗️ Gerando planta técnica da UHE {uhe_name}")
        print(f"📐 Escala: 1:{self.drawing_scale}")
        print(f"💾 Arquivo: {filename}")
        
        # Gerar conteúdo DXF
        dxf_content = self.create_dxf_content(uhe_data)
        
        try:
            with open(filename, 'w', encoding='utf-8') as f:
                f.write(dxf_content)
            
            print(f"✅ Planta DXF gerada com sucesso: {filename}")
            return filename
            
        except Exception as e:
            print(f"❌ Erro ao gerar arquivo DXF: {e}")
            return ""
    
