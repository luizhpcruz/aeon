    def list_available_uhes(self):
        """Listar UHEs disponíveis"""
        print("🏗️ UHEs DISPONÍVEIS NO SISTEMA AEON:")
        print("=" * 50)
        
        for i, uhe in enumerate(self.uhe_database, 1):
            print(f"{i}. 🏭 {uhe['name']}")
            print(f"   ⚡ {uhe['capacity_mw']:,} MW")
            print(f"   🏔️ Barragem: {uhe['dam_height_m']} m")
